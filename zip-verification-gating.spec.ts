// ------------------------------------------------------------------- helpers

async function ensureReady(page: Page): Promise<void> {
  await page.waitForLoadState('networkidle');
  await page.waitForSelector('body[data-pmr-ready]', { timeout: 10000 });
}

/** The per-file status element that carries the verification result. */
function statusOf(page: Page, id: number) {
  return page.locator(`[data-id="${id}"] .text-xs`).first();
}

/** Everything that decides whether the ZIP control is usable. */
async function probe(page: Page, selector: string) {
  return page.evaluate((sel) => {
    const el = document.querySelector(sel) as HTMLButtonElement | null;
    if (!el) return null;
    const cs = getComputedStyle(el);
    const rect = el.getBoundingClientRect();
    const panel = document.getElementById('results-panel');
    // A disabled button is not focusable, so this also proves the keyboard
    // cannot reach the control.
    el.focus();
    return {
      disabled: el.disabled,
      matchesDisabled: el.matches(':disabled'),
      ariaDisabled: el.getAttribute('aria-disabled'),
      hasHiddenClass: el.classList.contains('hidden'),
      display: cs.display,
      visibility: cs.visibility,
      rect: { w: Math.round(rect.width), h: Math.round(rect.height) },
      focusable: document.activeElement === el,
      panelHidden: panel ? panel.classList.contains('hidden') : null,
    };
  }, selector);
}

/**
 * Delay the RESOLUTION of the generated-output byte read inside the 'verifying'
 * window. Two independent triggers:
 *   __pmrDelayNeedle + __pmrDelayMs : first non-File read whose latin1 bytes
 *                                     contain the needle (one dirty output)
 *   __pmrDelayFirstCleanMs          : first non-File read at all
 * One-shot per page, so ZIP generation reads are never delayed.
 */
async function installDelayHook(page: Page): Promise<void> {
  await page.addInitScript(() => {
    const w = window as unknown as Record<string, unknown>;
    w.__pmrDelayMs = 0;
    w.__pmrDelayNeedle = '';
    w.__pmrDelayFirstCleanMs = 0;
    w.__pmrDelayUsed = false;
    w.__pmrDelayTrail = [];

    const original = Blob.prototype.arrayBuffer;
    Blob.prototype.arrayBuffer = function (this: Blob) {
      const meta = this as unknown as { size: number; type: string };
      return original.call(this).then(async (buf: ArrayBuffer) => {
        if (this instanceof File) return buf; // upload / strip reads
        if (w.__pmrDelayUsed) return buf;
        const bytes = new Uint8Array(buf);
        let latin = '';
        for (let i = 0; i < bytes.length; i++) latin += String.fromCharCode(bytes[i]);

        let ms = 0;
        let trigger = '';
        const needle = String(w.__pmrDelayNeedle || '');
        if (needle && latin.includes(needle)) {
          ms = Number(w.__pmrDelayMs) || 0;
          trigger = 'needle:' + needle;
        } else if (!needle && Number(w.__pmrDelayFirstCleanMs) > 0) {
          ms = Number(w.__pmrDelayFirstCleanMs);
          trigger = 'first-clean-read';
        }

        (w.__pmrDelayTrail as string[]).push(
          'read type=' + meta.type + ' size=' + meta.size + ' trigger=' + (trigger || 'none') + ' ms=' + ms,
        );
        if (ms > 0) {
          w.__pmrDelayUsed = true;
          await new Promise((r) => setTimeout(r, ms));
        }
        return buf;
      });
    };
  });
}

async function setDelay(page: Page, opts: { needle?: string; ms?: number; firstCleanMs?: number }) {
  await page.evaluate((o) => {
    const w = window as unknown as Record<string, unknown>;
    w.__pmrDelayNeedle = o.needle || '';
    w.__pmrDelayMs = o.ms || 0;
    w.__pmrDelayFirstCleanMs = o.firstCleanMs || 0;
    w.__pmrDelayUsed = false;
    w.__pmrDelayTrail = [];
  }, opts);
}

async function delayTrail(page: Page): Promise<string[]> {
  return page.evaluate(() => (window as unknown as { __pmrDelayTrail: string[] }).__pmrDelayTrail);
}

/** Real user click, tolerating a disabled (non-actionable) button. */
async function attemptRealClick(page: Page, selector: string): Promise<void> {
  await page
    .locator(selector)
    .click({ force: true, timeout: 3000 })
    .catch(() => undefined);
}

/**
 * Dispatch a synthetic click straight at the element, so the app's own handler
 * runs even while the button is `disabled`. This bypasses the UI gate on purpose
 * to prove the in-code defence-in-depth layer refuses unverified output.
 */
async function syntheticActivate(page: Page, selector: string): Promise<void> {
  await page.evaluate((sel) => {
    const el = document.querySelector(sel) as HTMLElement | null;
    el?.dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: true, composed: true }));
  }, selector);
}

/** Assert that `action` produces no download at all. */
async function expectNoDownload(page: Page, action: () => Promise<void>, ms = 2500): Promise<void> {
  let downloaded = false;
  const waiter = page
    .waitForEvent('download', { timeout: ms })
    .then(() => {
      downloaded = true;
    })
    .catch(() => undefined);
  await action();
  await waiter;
  expect(downloaded, 'no download must be produced').toBe(false);
}

/**
 * Forced (synthetic) activation deliberately bypasses `disabled`, so the in-code
 * gate is what is under test. Whatever the handler ships must consist of
 * VERIFIED-clean outputs only: the still-verifying entry must never be included,
 * and no privacy fixture value may appear in any shipped byte.
 *
 * Shipping nothing at all is also a correct outcome - that is what happens while
 * no verified output exists yet.
 */
async function expectForcedActivationShipsNoUnverified(page: Page, label: string): Promise<void> {
  const waiter = page.waitForEvent('download', { timeout: 5000 }).catch(() => null);
  await syntheticActivate(page, ZIP_BTN);
  const dl = await waiter;
  if (!dl) return;

  const name = dl.suggestedFilename();
  expect(name, `${label}: the still-verifying entry must never be shipped`).not.toContain('trailer');

  const saved = join(workDir, `${label.replace(/[^a-zA-Z0-9]+/g, '_')}-forced`);
  await dl.saveAs(saved);
  const bytes = readFileSync(saved);

  if (name.toLowerCase().endsWith('.zip')) {
    const JSZip = (await import('jszip')).default;
    const zip = await JSZip.loadAsync(bytes);
    for (const entryName of Object.keys(zip.files)) {
      expect(
        entryName,
        `${label}: the still-verifying entry must never be shipped`,
      ).not.toContain('trailer');
      const entryBytes = Buffer.from(await zip.files[entryName].async('uint8array'));
      expect(
        PRIVACY_VALUES.filter((v) => containsLatin1(entryBytes, v)),
        `${label}: a forced ZIP must carry no privacy values`,
      ).toEqual([]);
    }
    return;
  }

  expect(
    PRIVACY_VALUES.filter((v) => containsLatin1(bytes, v)),
    `${label}: a forced download must carry no privacy values`,
  ).toEqual([]);
}

/** The ZIP button must be genuinely unavailable (disabled + aria + not focusable). */
async function expectZipUnavailable(page: Page, label: string): Promise<void> {
  const p = await probe(page, ZIP_BTN);
  expect(p, `${label}: ZIP button must exist`).not.toBeNull();
  expect(p!.disabled, `${label}: ZIP button must be disabled`).toBe(true);
  expect(p!.matchesDisabled, `${label}: :disabled must match (UA blocks activation)`).toBe(true);
  expect(p!.ariaDisabled, `${label}: aria-disabled must mirror disabled`).toBe('true');
  expect(p!.focusable, `${label}: a disabled ZIP button must not be keyboard focusable`).toBe(false);
}

/** The ZIP button must be genuinely usable. */
async function expectZipAvailable(page: Page, label: string): Promise<void> {
  const p = await probe(page, ZIP_BTN);
  expect(p!.disabled, `${label}: ZIP button must be enabled`).toBe(false);
  expect(p!.ariaDisabled, `${label}: aria-disabled must mirror disabled`).toBe('false');
  expect(p!.visibility, `${label}: ZIP button must be visible`).toBe('visible');
  expect(p!.panelHidden, `${label}: results panel must be visible`).toBe(false);
}

