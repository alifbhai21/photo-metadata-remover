// TEST 5 - verification failure: failed output must NOT enter the ZIP.
// ===========================================================================
test('TEST 5 - verification failure keeps failed output out of the ZIP', async ({
  page,
}) => {
  test.setTimeout(120000);
  await installDelayHook(page);
  await page.goto(BASE);
  await ensureReady(page);
  await setDelay(page, { needle: NEEDLE, ms: 10000 });

  // item 1 = trailer -> auto-strip, verification held, will FAIL
  // item 2 = clean   -> manual removal, verifies clean
  // item 3 = clean   -> manual removal, verifies clean
  // Two verified items remain, so the real multi-entry ZIP path is exercised.
  await page.locator('#file-input').setInputFiles([trailerJpegPath, cleanJpegPath, cleanJpegPath2]);
  await expect(page.locator('#files-list > div[data-id]')).toHaveCount(3, { timeout: 30000 });
  await expect(statusOf(page, 1)).toContainText('Verifying clean output', { timeout: 30000 });

  await page.locator('#remove-2').click();
  await expect(page.locator('#remove-2')).toHaveText(/Success/, { timeout: 60000 });
  await expect(page.locator('#download-2')).toBeEnabled();
  await page.locator('#remove-3').click();
  await expect(page.locator('#remove-3')).toHaveText(/Success/, { timeout: 60000 });
  await expect(page.locator('#download-3')).toBeEnabled();

  // 2 verified + 1 still verifying => ZIP must stay unavailable.
  await expectZipUnavailable(page, 'TEST 5 (2 passed + 1 failing)');
  await expectNoDownload(page, () => attemptRealClick(page, ZIP_BTN));

  await expect(statusOf(page, 1)).toContainText('Verification failed', { timeout: 90000 });
  await expectZipAvailable(page, 'TEST 5 (failed settled, 2 verified remain)');

  const downloadPromise = page.waitForEvent('download', { timeout: 60000 });
  await syntheticActivate(page, ZIP_BTN);
  const zipDownload = await downloadPromise;
  const zipPath = join(workDir, 'test5-failed.zip');
  await zipDownload.saveAs(zipPath);
  const zipBytes = readFileSync(zipPath);

  const JSZip = (await import('jszip')).default;
  const zip = await JSZip.loadAsync(zipBytes);
  const names = Object.keys(zip.files);
  expect(names, 'ZIP must contain exactly the verified items').toHaveLength(2);
  expect(names.join(' '), 'the failed output must never enter the ZIP').not.toContain('trailer');
  expect(names.join(' ')).toContain('gate-one');
  expect(names.join(' ')).toContain('gate-two');

  for (const name of names) {
    const entryBytes = await zip.files[name].async('uint8array');
    expect(PRIVACY_VALUES.filter((v) => containsLatin1(Buffer.from(entryBytes), v))).toEqual([]);
    expect(await privacyKeysInBytes(Buffer.from(entryBytes), 'image/jpeg')).toEqual([]);
  }

  console.log('TEST 5 PASSED: failed output excluded from ZIP; only verified items shipped');
  console.log('[TEST 5] zip entries:', JSON.stringify(names));
});

