// TEST 9 - responsive functional contract (all six viewports), asserted in the
// loop below. The former standalone TEST 9 asserted a deprecated, incorrect
// contract (`hidden` class / visibility "hidden" / display !== "inline-flex").
// Real product behaviour: the control stays rendered and dimmed (Tailwind's
// `hidden` class is overridden by `inline-flex`), but it is genuinely inert -
// `disabled`, `aria-disabled="true"`, not focusable, and clicking it starts no
// download.
// ===========================================================================
// ===========================================================================
// TEST 9 - responsive: ZIP gating observable and enforced at all viewports.
// ===========================================================================
for (const vp of VIEWPORTS) {
  test(`TEST 9 [${vp.label} ${vp.width}x${vp.height}] ZIP inert while a verified item sits beside a verifying one`, async ({
    page,
  }) => {
    test.setTimeout(120000);
    await page.setViewportSize({ width: vp.width, height: vp.height });
    await installDelayHook(page);
    await page.goto(BASE);
    await ensureReady(page);
    await setDelay(page, { needle: NEEDLE, ms: 15000 });

    // Item 1 = trailer -> held open in the 'verifying' window.
    // Item 2 = metadata-bearing JPEG -> removed and verified clean.
    // This is the dangerous state: a verified-clean output really exists, so a
    // gate that tested `cleanBlob` alone would open the control right here.
    await page.locator('#file-input').setInputFiles([trailerJpegPath, cleanJpegPath]);
    await expect(page.locator('#files-list > div[data-id]')).toHaveCount(2, { timeout: 30000 });
    await expect(statusOf(page, 1)).toContainText('Verifying clean output', { timeout: 30000 });

    await page.locator('#remove-2').click();
    await expect(page.locator('#download-2')).toBeEnabled({ timeout: 60000 });

    // Positive control: a verified-clean item really does exist right now.
    await expectZipUnavailable(page, `TEST 9 [${vp.label}] 1 verified + 1 verifying`);

    // Functional contract: genuinely inert, not merely styled.
    const probe = await page.evaluate(() => {
      const b = document.querySelector('#download-all-btn') as HTMLButtonElement | null;
      if (!b) return { missing: true };
      b.focus();
      return {
        missing: false,
        disabled: b.disabled,
        ariaDisabled: b.getAttribute('aria-disabled'),
        focusable: document.activeElement === b,
      };
    });
    expect(probe.missing, 'button must exist').toBe(false);
    expect(probe.disabled, `TEST 9 [${vp.label}] button must be disabled`).toBe(true);
    expect(probe.ariaDisabled, `TEST 9 [${vp.label}] aria-disabled must be true`).toBe('true');
    expect(probe.focusable, `TEST 9 [${vp.label}] disabled control must not be focusable`).toBe(false);

    // A real click must start no download at all.
    await expectNoDownload(page, () => attemptRealClick(page, ZIP_BTN));

    console.log(
      `TEST 9 [${vp.label}] PASSED: ZIP inert (disabled + aria-disabled + not focusable + no download) at ${vp.width}x${vp.height}`,
    );
  });
}
