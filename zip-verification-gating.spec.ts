/**
 * ZIP verification gating - permanent regression spec.
 *
 * The integrity gap this pins down:
 *   `#download-all-btn` was un-hidden/usable as soon as ANY item had a
 *   `cleanBlob`, but `cleanBlob` is published BEFORE verification runs. So the
 *   batch ZIP could be built - and downloaded - while an entry was still
 *   `verifyStatus === 'verifying'`, shipping bytes that the app's own verifier
 *   then rejected. A second defect compounded it: the button carries both
 *   `hidden` and `inline-flex`, and `inline-flex` wins in the compiled Tailwind
 *   output, so `classList.toggle('hidden', ...)` never actually hid it - and the
 *   button was never `disabled` either.
 *
 * What is proven here (all against the real generated bytes):
 *   1  no verified output yet            -> ZIP disabled, no download
 *   2  1 verified + 1 verifying          -> ZIP disabled, no download
 *   3  Remove All + held verification    -> ZIP disabled, no download
 *   4  out-of-order verification         -> ZIP disabled until all settle
 *   5  verification failure              -> failed output never enters the ZIP
 *   6  single-item fallback              -> both download paths refuse
 *   7  stale batch                       -> old batch never affects the new one
 *   8  actual ZIP content                -> only passed items, no privacy values
 *   9  all six viewports                 -> real, observable disabled state
 *
 * Verification is NEVER faked: the only instrumentation delays the RESOLUTION of
 * the generated-output byte read (`Blob.prototype.arrayBuffer` for non-File
 * blobs), so the app still reads, re-parses and re-classifies the same bytes.
 * It only widens the 'verifying' window so that window is observable.
 *
 * Run with the dev server up: npx playwright test zip-verification-gating.spec.ts
 */
