// TEST 2 - 1 verified + 1 verifying: ZIP must stay disabled until it settles.
// ===========================================================================
test('TEST 2 - 1 verified + 1 verifying: ZIP stays disabled and downloads nothing', async ({ page }) => {
  test.setTimeout(120000);
  await installDelayHook(page);
  await page.goto(BASE);
  await ensureReady(page);
  // Hold ONLY the trailer's output in the 'verifying' window (dirty bytes).
  await setDelay(page, { needle: NEEDLE, ms: 12000 });

  // item 1 = trailer -> auto-strip starts immediately (verification held)
  // item 2 = clean   -> manual removal, verifies normally
  await page.locator('#file-input').setInputFiles([trailerJpegPath, cleanJpegPath]);
  await expect(page.locator('#files-list > div[data-id]')).toHaveCount(2, { timeout: 30000 });
  await expect(statusOf(page, 1)).toContainText('Verifying clean output', { timeout: 30000 });

  await expect(page.locator('#remove-2')).toHaveText('Remove metadata', { timeout: 30000 });
  await page.locator('#remove-2').click();
  await expect(page.locator('#remove-2')).toHaveText(/Success/, { timeout: 30000 });
  await expect(page.locator('#download-2')).toBeEnabled();

  // 1 verified-clean + 1 verifying => ZIP must NOT be usable.
  expect((await statusOf(page, 1).textContent()) || '', 'item 1 is still verifying').toContain(
    'Verifying clean output',
  );
  await expectZipUnavailable(page, 'TEST 2 (1 verified + 1 verifying)');
  // Real UI click: the disabled control starts nothing at all.
  await expectNoDownload(page, () => attemptRealClick(page, ZIP_BTN));
  // Forced activation bypasses `disabled`, so the in-code gate is what must
  // refuse the still-verifying entry (only verified items may ever ship).
  await expectForcedActivationShipsNoUnverified(page, 'TEST 2');

  // Any forced path must never ship the still-verifying (dirty) entry: it was
  // rejected by the app's own verifier, so it can never be "passed".
  await expect(statusOf(page, 1)).toContainText('Verification failed', { timeout: 90000 });

  // Once every item has settled, the control opens again and - because only one
  // verified entry remains - the single-item path delivers exactly that file.
  // (This also acts as the positive control proving synthetic activation really
  // does reach the app's handler, so the negative assertions above are real.)
  await expectZipAvailable(page, 'TEST 2 (after verification settled)');
  const downloadPromise = page.waitForEvent('download', { timeout: 60000 });
  await syntheticActivate(page, ZIP_BTN);
  const settledDownload = await downloadPromise;
  expect(settledDownload.suggestedFilename(), 'only the verified entry is delivered').toBe(
    'gate-one-clean.jpg',
  );
  const settledSaved = join(workDir, 'test2-settled.jpg');
  await settledDownload.saveAs(settledSaved);
  const settledBytes = readFileSync(settledSaved);
  expect(PRIVACY_VALUES.filter((v) => containsLatin1(settledBytes, v))).toEqual([]);
  expect(await privacyKeysInBytes(settledBytes, 'image/jpeg')).toEqual([]);

  console.log('TEST 2 PASSED: ZIP stayed disabled; no download while verifying');
  console.log('[TEST 2] delay trail:', JSON.stringify(await delayTrail(page)));
});

