  await expect(statusOf(page, 2)).toContainText('Metadata removed successfully');
  await expect(page.locator('#download-1')).toBeEnabled();
  await expect(page.locator('#download-2')).toBeEnabled();
  await expectZipAvailable(page, 'TEST 7 (Batch B after Batch A settled)');

  console.log('TEST 7 PASSED: Batch A did not affect Batch B ZIP');
